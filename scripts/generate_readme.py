#!/usr/bin/env python3
"""Generate README.md from data/entries/*.yml."""

from __future__ import annotations

import datetime as dt
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.stderr.write("PyYAML is required: pip install pyyaml\n")
    raise SystemExit(1)

ROOT = Path(__file__).resolve().parents[1]
ENTRIES_DIR = ROOT / "data" / "entries"
README_PATH = ROOT / "README.md"

TYPES = {"single", "component", "collection"}
CATEGORIES = (
    "create",
    "workspace",
    "components",
    "motion",
    "inspiration",
    "plugin",
)
CATEGORY_TITLES = {
    "create": "Create",
    "workspace": "Workspace",
    "components": "Components",
    "motion": "Motion",
    "inspiration": "Inspiration",
    "plugin": "Plugins",
}
REQUIRED = (
    "name",
    "url",
    "type",
    "category",
    "blurb",
    "reason",
    "status",
    "updated",
)


def fail(message: str) -> None:
    raise SystemExit(message)


def as_text(value: object) -> str:
    if value is None:
        return ""
    return str(value).strip()


def load_entries() -> list[dict]:
    paths = sorted(ENTRIES_DIR.glob("*.yml"))
    if not paths:
        fail(f"No entries in {ENTRIES_DIR}")

    entries: list[dict] = []
    seen_urls: dict[str, str] = {}
    seen_names: dict[str, str] = {}

    for path in paths:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
        if not isinstance(data, dict):
            fail(f"{path.name}: expected a mapping")

        missing = [key for key in REQUIRED if not as_text(data.get(key))]
        if missing:
            fail(f"{path.name}: missing {', '.join(missing)}")

        if data["type"] not in TYPES:
            fail(f"{path.name}: invalid type {data['type']!r}")
        if data["category"] not in CATEGORIES:
            fail(f"{path.name}: invalid category {data['category']!r}")
        if data["status"] != "published":
            fail(f"{path.name}: status must be 'published'")

        url = as_text(data["url"])
        if not url.startswith("https://"):
            fail(f"{path.name}: url must be an https URL")

        updated = data["updated"]
        if isinstance(updated, dt.date):
            updated = updated.isoformat()
        else:
            updated = as_text(updated)
        try:
            dt.date.fromisoformat(updated)
        except ValueError:
            fail(f"{path.name}: updated must be an ISO date (YYYY-MM-DD)")

        stack = data.get("stack") or []
        if stack is None:
            stack = []
        if not isinstance(stack, list) or not all(isinstance(item, str) and item.strip() for item in stack):
            fail(f"{path.name}: stack must be a list of strings")

        name = as_text(data["name"])
        name_key = name.casefold()
        if name_key in seen_names:
            fail(f"{path.name}: duplicate name {name!r} (also in {seen_names[name_key]})")
        if url in seen_urls:
            fail(f"{path.name}: duplicate url {url} (also in {seen_urls[url]})")
        seen_names[name_key] = path.name
        seen_urls[url] = path.name

        notes = data.get("notes")
        if notes is not None and not isinstance(notes, str):
            fail(f"{path.name}: notes must be a string")

        pricing = data.get("pricing")
        if pricing is not None and not isinstance(pricing, str):
            fail(f"{path.name}: pricing must be a string")

        entries.append(
            {
                "name": name,
                "url": url,
                "type": data["type"],
                "category": data["category"],
                "blurb": " ".join(as_text(data["blurb"]).split()),
                "stack": [item.strip() for item in stack],
                "pricing": as_text(pricing),
                "reason": " ".join(as_text(data["reason"]).split()),
                "notes": " ".join(as_text(notes).split()),
                "status": "published",
                "updated": updated,
            }
        )

    return entries


def render(entries: list[dict]) -> str:
    lines = [
        "# awesome-aigc-design-tools",
        "",
        "Collect great AIGC powered ui ux design tools.",
        "",
        "This README is generated from [`data/entries/`](data/entries/). Edit the YAML files, then regenerate. Do not edit this file by hand.",
        "",
        "```bash",
        "python3 scripts/generate_readme.py",
        "```",
        "",
        "See [scripts/README.md](scripts/README.md).",
        "",
    ]

    grouped: dict[str, list[dict]] = {category: [] for category in CATEGORIES}
    for entry in entries:
        grouped[entry["category"]].append(entry)

    for category in CATEGORIES:
        items = grouped[category]
        if not items:
            continue
        items.sort(key=lambda entry: entry["name"].casefold())
        lines.append(f"## {CATEGORY_TITLES[category]}")
        lines.append("")
        for entry in items:
            lines.append(f"- [{entry['name']}]({entry['url']}) — {entry['blurb']}")
            lines.append(f"  > 推荐理由：{entry['reason']}")
            meta: list[str] = []
            if entry["stack"]:
                meta.append("Stack: " + ", ".join(entry["stack"]))
            if entry["pricing"]:
                meta.append("Pricing: " + entry["pricing"])
            if meta:
                lines.append("  > " + " · ".join(meta))
            if entry["notes"]:
                lines.append(f"  > 注意：{entry['notes']}")
            lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    entries = load_entries()
    README_PATH.write_text(render(entries), encoding="utf-8")
    print(f"Wrote {README_PATH.relative_to(ROOT)} ({len(entries)} published entries)")


if __name__ == "__main__":
    main()
